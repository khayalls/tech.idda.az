// Generates src/styles/tokens.css from design/tokens.json.
// The same JSON feeds the Figma variables (collections: Primitives, Color, Spacing, Layout),
// so code and design stay in sync. Run: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));
const out = resolve(root, "src/styles/tokens.css");

const px = (n) => `${+n.toFixed(4)}px`;
const VIEW_MIN = 375;
const VIEW_MAX = 1440;

// Fluid value between a mobile and a desktop size, clamped at both ends.
const fluid = (min, max) => {
  if (min === max) return px(max);
  const slope = (max - min) / (VIEW_MAX - VIEW_MIN);
  const intercept = min - slope * VIEW_MIN;
  return `clamp(${px(min)}, ${px(intercept)} + ${+(slope * 100).toFixed(4)}vw, ${px(max)})`;
};

const ref = (path) => {
  if (path === "white") return "var(--color-white)";
  const [group, step] = path.split(".");
  return group === "alpha" ? `var(--color-${step})` : `var(--color-${group}-${step})`;
};

const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");

const lines = [];
const L = (s = "") => lines.push(s);

L("/* Generated by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand. */");
L();
L("/* Primitives, semantic roles, layout. */");
L(":root {");
for (const fam of ["blue", "cyan", "neutral"]) {
  for (const [step, hex] of Object.entries(t.color[fam])) L(`  --color-${fam}-${step}: ${hex};`);
}
L(`  --color-white: ${t.color.white};`);
for (const [name, [hex, a]] of Object.entries(t.alpha)) L(`  --color-${name}: rgb(${hexToRgb(hex)} / ${a});`);
L();
for (const [name, path] of Object.entries(t.semantic)) L(`  --${name}: ${ref(path)};`);
L();
const [g0, g1, g2] = t.gradient.brand.map((s) => s.split("@"));
L(`  --gradient-brand: linear-gradient(180deg, ${ref(g0[0])} ${+g0[1] * 100}%, ${ref(g1[0])} ${+g1[1] * 100}%, ${ref(g2[0])} ${+g2[1] * 100}%);`);
const [n0, n1] = t.gradient.night.map((s) => s.split("@"));
L(`  --gradient-night: linear-gradient(180deg, ${ref(n0[0])} ${+n0[1] * 100}%, ${ref(n1[0])} ${+n1[1] * 100}%);`);
L();
const { desktop, tablet, mobile } = t.layout;
L(`  --max-width: ${px(t.layout.maxWidth)};`);
L(`  --page-margin: ${px(mobile.margin)};`);
L(`  --grid-gutter: ${px(mobile.gutter)};`);
L(`  --grid-cols: ${mobile.cols};`);
L(`  --section-y: ${px(mobile.sectionY)};`);
L(`  --dot-pitch-hero: ${t.dot.pitchHero};`);
L(`  --dot-pitch-display: ${t.dot.pitchDisplay};`);
L("}");
L();
L(`@media (min-width: ${tablet.min}px) {`);
L(`  :root { --page-margin: ${px(tablet.margin)}; --grid-gutter: ${px(tablet.gutter)}; --grid-cols: ${tablet.cols}; --section-y: ${px(tablet.sectionY)}; }`);
L("}");
L(`@media (min-width: ${desktop.min}px) {`);
L(`  :root { --page-margin: ${px(desktop.margin)}; --grid-gutter: ${px(desktop.gutter)}; --grid-cols: ${desktop.cols}; --section-y: ${px(desktop.sectionY)}; }`);
L("}");
L();

// Tailwind theme: reset the default palette and expose only system values.
L("@theme {");
L("  --color-*: initial;");
for (const fam of ["blue", "cyan", "neutral"]) {
  for (const [step, hex] of Object.entries(t.color[fam])) L(`  --color-${fam}-${step}: ${hex};`);
}
L(`  --color-white: ${t.color.white};`);
L("  --color-transparent: transparent;");
L("  --color-current: currentColor;");
L();
L("  /* Spacing: Tailwind multiplies --spacing, so p-4 = 16px. Use only 4 × {1,2,3,4,6,8,10,12,16,20,24,32,40}. */");
L("  --spacing: 4px;");
L();
L(`  --breakpoint-md: ${tablet.min}px;`);
L(`  --breakpoint-xl: ${desktop.min}px;`);
L();
for (const [k, v] of Object.entries(t.radius)) L(`  --radius-${k}: ${px(v)};`);
L();
L("  --font-sans: var(--font-geist-sans), ui-sans-serif, system-ui, sans-serif;");
L("  --font-weight-normal: 400;");
L("  --font-weight-medium: 500;");
L();
L(`  --ease-out: ${t.motion.easeOut};`);
L();
L("  /* Type scale: Major Third (16 × 1.25ⁿ) rounded to a 4px grid, fluid between mobile and desktop. */");
const byName = Object.fromEntries(t.type.map((s) => [s.name, s]));
for (const s of t.type) {
  const name = s.name.replace("/", "-");
  const m = byName[t.typeMobile[s.name]] ?? s;
  L(`  --text-${name}: ${fluid(m.size, s.size)};`);
  L(`  --text-${name}--line-height: ${fluid(m.lineHeight, s.lineHeight)};`);
  L(`  --text-${name}--letter-spacing: ${+(s.tracking / 100).toFixed(4)}em;`);
  L(`  --text-${name}--font-weight: ${s.weight === "Medium" ? 500 : 400};`);
}
L("}");
L();
// Semantic roles as Tailwind colours, e.g. bg-page, text-primary, text-on-dark, bg-btn-primary.
const TW = {
  "bg-page": "page", "bg-surface": "surface", "bg-inverse": "night", "bg-inverse-deep": "night-deep",
  "text-primary": "primary", "text-secondary": "secondary", "text-tertiary": "tertiary", "text-muted": "muted",
  "text-inverse": "on-dark", "text-inverse-secondary": "on-dark-secondary", "text-accent": "accent",
  "border-subtle": "line", "border-inverse": "line-on-dark",
  "button-primary-bg": "btn-primary", "button-primary-text": "btn-primary-fg",
  "button-light-bg": "btn-light", "button-light-text": "btn-light-fg", "button-glass-bg": "btn-glass",
  "dot-led-on": "led-on", "dot-led-off": "led-off", "dot-inverse": "dot-light",
};
L("@theme inline {");
for (const name of Object.keys(t.semantic)) {
  if (!TW[name]) throw new Error(`No Tailwind alias for semantic token ${name}`);
  L(`  --color-${TW[name]}: var(--${name});`);
}
L("}");
L();

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`tokens → ${out}`);
